// Generates legal/sbom.cdx.json (CycloneDX 1.5) and legal/THIRD_PARTY_LICENSES.md
// from package-lock.json. Run: node scripts/sbom.mjs   (CI checks the output is up to date)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));

// Production dependencies only (what ships inside the apps / server).
const comps = new Map();
for (const [p, info] of Object.entries(lock.packages ?? {})) {
  if (!p.startsWith('node_modules/') && !p.includes('/node_modules/')) continue;
  if (info.dev || info.devOptional || info.link) continue;
  const name = info.name ?? p.slice(p.lastIndexOf('node_modules/') + 'node_modules/'.length);
  const key = `${name}@${info.version}`;
  if (comps.has(key)) continue;
  const lic = typeof info.license === 'string' ? info.license : Array.isArray(info.license) ? info.license.join(' OR ') : 'UNKNOWN';
  comps.set(key, { name, version: info.version, license: lic });
}
const list = [...comps.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const sbom = {
  bomFormat: 'CycloneDX',
  specVersion: '1.5',
  version: 1,
  metadata: { component: { type: 'application', name: 'fristy-remote', version: '0.2' } },
  components: list.map((c) => ({
    type: 'library',
    name: c.name,
    version: c.version,
    purl: `pkg:npm/${c.name.replace('@', '%40')}@${c.version}`,
    licenses: c.license === 'UNKNOWN' ? [] : [{ expression: c.license }]
  }))
};
fs.writeFileSync(path.join(root, 'legal', 'sbom.cdx.json'), JSON.stringify(sbom, null, 2) + '\n');

const byLic = new Map();
for (const c of list) byLic.set(c.license, [...(byLic.get(c.license) ?? []), c]);
const COPYLEFT = /GPL|AGPL|LGPL|MPL|EPL|CDDL|SSPL|EUPL/i;
const flagged = list.filter((c) => COPYLEFT.test(c.license) || c.license === 'UNKNOWN');
// Reviewed decisions for flagged packages (keep in sync when new ones appear).
const REVIEWED = {
  lightningcss: 'Build-time CSS tool used by Tailwind/Vite; it is not part of the shipped app bundle. MPL-2.0 file-level copyleft would only apply to modified lightningcss files – none are modified.',
  'node-forge': 'Dual licensed "BSD-3-Clause OR GPL-2.0": used under **BSD-3-Clause**.'
};
const reviewNote = (n) => REVIEWED[n] ?? REVIEWED[n.replace(/-(android|darwin|freebsd|linux|win32).*$/, '')] ?? '**Not yet reviewed – release-blocking.**';

let md = `---
title: Third-Party Licenses
title_he: רישיונות צד שלישי
version: generated
updated: generated by scripts/sbom.mjs from package-lock.json
---

> Generated file – do not edit by hand. Run \`node scripts/sbom.mjs\`. Machine-readable SBOM: \`legal/sbom.cdx.json\` (CycloneDX 1.5).
> Full licence texts are distributed with each package in \`node_modules/<package>/LICENSE\` and must be included in release artifacts [see checklist].

# Third-Party Licenses

**${list.length} production npm packages.** Licence summary:

| Licence | Packages |
|---|---|
${[...byLic.entries()].sort((a, b) => b[1].length - a[1].length).map(([l, cs]) => `| ${l} | ${cs.length} |`).join('\n')}

## Needs review
${flagged.length ? flagged.map((c) => `- \`${c.name}@${c.version}\` – **${c.license}** – ${reviewNote(c.name)}`).join('\n') : '- None: no copyleft or unknown licences among production npm packages.'}

## Components not listed in package-lock.json
| Component | Licence | Notes |
|---|---|---|
| Electron runtime (Chromium, Node.js, V8) | MIT + Chromium's BSD-style and third-party licences | Electron ships \`LICENSES.chromium.html\` – must be included in the installer (electron-builder does this by default) |
| FFmpeg (bundled with Electron as ffmpeg.dll) | LGPL-2.1+ | Dynamically linked, unmodified, proprietary codecs not enabled – LGPL notice required |
| NSIS (Windows installer) | zlib/libpng | Installer stub |
| Hermes / React Native / Expo (phone app) | MIT | Included in the list above where installed via npm |
| Lucide icons | ISC | Included above (\`lucide-react\`, \`lucide-react-native\`) |
| Fonts | – | System fonts only; no font files distributed |
| Map tiles / map data | – | Not used |
| AI models | – | Not used |
| Cloudflare Workers, D1, Durable Objects; GitHub Releases; ntfy.sh | Service terms | External services, not redistributed |

## All packages
| Package | Version | Licence |
|---|---|---|
${list.map((c) => `| ${c.name} | ${c.version} | ${c.license} |`).join('\n')}
`;
fs.writeFileSync(path.join(root, 'legal', 'THIRD_PARTY_LICENSES.md'), md);
const unreviewed = flagged.filter((f) => reviewNote(f.name).startsWith('**Not yet'));
console.log(`${list.length} packages; flagged ${flagged.length}; unreviewed ${unreviewed.length}`);
for (const f of unreviewed) console.log(`  UNREVIEWED ${f.name}@${f.version} ${f.license}`);
if (process.argv.includes('--check') && unreviewed.length) process.exit(1);
